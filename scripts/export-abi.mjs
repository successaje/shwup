// Copies the compiled ShwUp ABI into the web app as a typed `as const` module.
// Run `forge build` in contracts/ first.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = JSON.parse(readFileSync(join(root, "contracts/out/ShwUp.sol/ShwUp.json"), "utf8"));
const out = join(root, "web/src/lib/contracts/shwup-abi.ts");

writeFileSync(
  out,
  `// Generated by scripts/export-abi.mjs from contracts/out — do not edit by hand.\n` +
    `export const shwupAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`wrote ${out}`);
